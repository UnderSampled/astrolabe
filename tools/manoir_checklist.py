#!/usr/bin/env python3
"""Write docs/astrolabe/manoir-checklist.md from what can be measured today."""
import collections
import json
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parent.parent
behaviors = Path(sys.argv[1]) if len(sys.argv) > 1 else None
hand = root/'tools/behaviors/manoir-items.md'


def main():
    tiers = collections.Counter(line.split('\t')[3] for line in (root/'src/openspace/save_keys_manoir.tsv').read_text().splitlines())
    models = root/'godot/generated/hype/levels/manoir/ai/models'
    text = ''.join(path.read_text(errors='replace') for path in models.rglob('*.gd'))
    stand_ins = collections.Counter(re.findall(r'stand_in\("([^"]+)"', text))
    lines = ['# Manoir checklist', '', 'Generated by `tools/manoir_checklist.py`. Items below the measured sections are kept by hand in',
             '`tools/behaviors/manoir-items.md`.', '', '## Save fields', '',
             f'{sum(tiers.values())} record identities in the supplied slot: {tiers["verified"]} verified, {tiers["source"]} read from source, {tiers["unknown"]} still unknown.', '',
             '## AI script functions', '',
             f'{len(list(models.rglob("*.gd")))} compiled models. {sum(stand_ins.values())} stand-in sites across {len(stand_ins)} ids:', '']
    lines += [f'- `{key}`: {count}' for key, count in stand_ins.most_common()]
    lines += ['', '## Behaviors tested against Orrery', '']
    if behaviors and behaviors.is_file():
        rows = json.loads(behaviors.read_text())
        matched = sum(row['state'] == 'match' for row in rows)
        lines += [f'{matched} of {len(rows)} scenarios match. Same keys sent to both engines; timing is not judged.', '',
                  '| Scenario | Result | Actions in port | Moved, original | Moved, port |', '| --- | --- | --- | --- | --- |']
        lines += [f'| {row["name"]} | {row["state"]} | {" ".join(map(str, row["port_actions"]))} | {row["original_moved"]} | {row["port_moved"]} |' for row in rows]
    lines += ['', hand.read_text().rstrip(), '']
    (root/'docs/astrolabe/manoir-checklist.md').write_text('\n'.join(lines))


if __name__ == '__main__':
    sys.exit(main())
